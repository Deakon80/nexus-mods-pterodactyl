// Creates or updates a Nexus Collection from the browser with the user's own API key, through
// Nexus's v3 API (https://api.nexusmods.com/v3, ApiKeyAuth): upload session → upload the
// collection package → finalise → wait until available → create the collection or a new revision.
// New revisions start as drafts; the user publishes on Nexus.

import { md5, zip } from './archive';
import type { Installed } from './mods';
import { isMainFile, modFiles, type NexusFile, type NexusMod } from './nexus';

const API = 'https://api.nexusmods.com/v3';
const APP_HEADERS = { 'Application-Name': 'Nexus Mods for Pterodactyl', 'Application-Version': '1.0.0' };
const POLL_INTERVAL_MS = 2000;
const POLL_MAX_ATTEMPTS = 150; // 5 minutes, as Vortex waits
const NAME_MAX = 36; // CollectionManifestInfo.name and EditCollectionRequest.name in the v3 spec

export interface CollectionRef {
    collection_id: string;
    slug: string;
    owner: string;
    revision_number: number;
    revision_status: string;
}

export interface CollectionInput {
    apiKey: string;
    author: string;
    domain: string;
    gameName: string;
    serverName: string;
    loader: NexusMod | null;
    mods: Installed[];
    existing: CollectionRef | null;
    onStep: (text: string) => void;
    /** Uploads the package through the panel, for when storage blocks the browser. Gets no API key. */
    relay: (url: string, filename: string, contentBase64: string) => Promise<void>;
}

export const collectionUrl = (domain: string, slug: string) => `https://www.nexusmods.com/games/${domain}/collections/${slug}`;

const toBase64 = (bytes: Uint8Array) => btoa(Array.from(bytes, (byte) => String.fromCharCode(byte)).join(''));
const hexToBytes = (hex: string) => Uint8Array.from(hex.match(/../g) ?? [], (pair) => parseInt(pair, 16));

async function v3<T>(apiKey: string, method: string, path: string, body?: unknown): Promise<T> {
    const response = await fetch(API + path, {
        method,
        headers: { apikey: apiKey, ...APP_HEADERS, ...(body === undefined ? {} : { 'Content-Type': 'application/json' }) },
        body: body === undefined ? undefined : JSON.stringify(body),
    });
    const text = await response.text();
    const json = text ? (JSON.parse(text) as { data?: T; detail?: string; title?: string }) : {};
    if (!response.ok) {
        const reason = json.detail || json.title || `HTTP ${response.status}`;
        if (response.status === 403) {
            throw new Error(`Nexus Mods refused: ${reason}. Only the account that created a collection can update it.`);
        }
        throw new Error(`Nexus Mods: ${reason}`);
    }
    return json.data as T;
}

/** Nexus collection names are 3 to 36 characters: "<server> mods" when it fits, else the server name cut to fit. */
export function collectionName(serverName: string, gameName: string): string {
    const server = serverName.trim().replace(/\s+/g, ' ');
    if (server.length < 3) {
        return `${gameName} server mods`.slice(0, NAME_MAX).trim();
    }
    return `${server} mods`.length <= NAME_MAX ? `${server} mods` : server.slice(0, NAME_MAX).trim();
}

/** The manifest Nexus stores for the collection, and the collection.json players' Vortex installs from. */
function manifests(input: CollectionInput, loaderFile: NexusFile | null) {
    // Nexus needs a file on every entry. Mods pin the file the server runs ("exact");
    // the loader starts at its newest main file and follows updates ("latest").
    const entries = [
        ...(input.loader && loaderFile
            ? [{ name: input.loader.name, version: loaderFile.version ?? input.loader.version, modId: input.loader.modId, fileId: loaderFile.file_id, updatePolicy: 'latest' }]
            : []),
        ...input.mods.map((item) => ({ name: item.mod_name, version: item.version ?? '', modId: item.mod_id, fileId: item.file_id, updatePolicy: 'exact' })),
    ];
    const name = collectionName(input.serverName, input.gameName);
    const summary = `The mods the ${input.serverName} server runs, so players can match it in one click.`.slice(0, 255);
    const description = `${summary}\n\nGenerated by Nexus Mods for Pterodactyl from the server's installed mods.`;

    const collectionJson = {
        info: {
            author: input.author,
            authorUrl: '',
            name,
            description,
            installInstructions: '',
            domainName: input.domain,
            gameVersions: [],
        },
        mods: entries.map((entry) => ({
            name: entry.name,
            version: entry.version,
            optional: false,
            domainName: input.domain,
            source: { type: 'nexus', modId: entry.modId, fileId: entry.fileId, updatePolicy: entry.updatePolicy },
            author: '',
            details: {},
            phase: 0,
        })),
        modRules: [],
    };

    const payload = {
        adult_content: false,
        collection_schema_id: 1,
        collection_manifest: {
            info: { author: input.author, name, summary, description, domain_name: input.domain },
            mods: entries.map((entry) => ({
                name: entry.name,
                version: entry.version,
                optional: false,
                domain_name: input.domain,
                source: { type: 'nexus', mod_id: String(entry.modId), file_id: String(entry.fileId), update_policy: entry.updatePolicy },
            })),
        },
    };

    return { collectionJson, payload, name };
}

export async function publishCollection(input: CollectionInput): Promise<CollectionRef> {
    const { apiKey } = input;
    let loaderFile: NexusFile | null = null;
    if (input.loader) {
        input.onStep('Looking up the mod loader’s current file…');
        loaderFile = (await modFiles(apiKey, input.domain, input.loader.modId)).find(isMainFile) ?? null;
        if (!loaderFile) {
            throw new Error(`${input.loader.name} has no main file on Nexus Mods to add. Nothing was created.`);
        }
    }
    const { collectionJson, payload, name } = manifests(input, loaderFile);

    input.onStep('Packaging the mod list…');
    const archive = zip([{ name: 'collection.json', data: new TextEncoder().encode(JSON.stringify(collectionJson, null, 2)) }]);
    const filename = `collection_${Date.now()}.zip`;

    input.onStep('Uploading to Nexus Mods…');
    const digest = md5(archive);
    const upload = await v3<{ id: string; presigned_url: string }>(apiKey, 'POST', '/uploads', { size_bytes: archive.length, filename, md5: digest });
    // The upload session is presigned against exactly these headers; Content-MD5 because we sent an md5.
    let put: Response | null = null;
    try {
        put = await fetch(upload.presigned_url, {
            method: 'PUT',
            headers: {
                'Content-Type': 'application/octet-stream',
                'Content-Disposition': `attachment; filename="${filename}"`,
                'Content-MD5': toBase64(hexToBytes(digest)),
            },
            body: new Blob([archive.slice().buffer]),
        });
    } catch {
        // Storage does not allow uploads from web pages: the panel relays the package (never the key).
        input.onStep('Uploading to Nexus Mods through the panel…');
        await input.relay(upload.presigned_url, filename, toBase64(archive));
    }
    if (put !== null && !put.ok) {
        throw new Error(`Nexus Mods storage refused the upload (HTTP ${put.status}). Nothing was created.`);
    }

    await v3(apiKey, 'POST', `/uploads/${upload.id}/finalise`);
    input.onStep('Waiting for Nexus Mods to process the upload…');
    for (let attempt = 0; ; attempt++) {
        const state = await v3<{ state: string }>(apiKey, 'GET', `/uploads/${upload.id}`);
        if (state.state === 'available') {
            break;
        }
        if (attempt >= POLL_MAX_ATTEMPTS) {
            throw new Error('Nexus Mods did not finish processing the upload within 5 minutes. Try again later.');
        }
        await new Promise((resolve) => setTimeout(resolve, POLL_INTERVAL_MS));
    }

    if (input.existing === null) {
        input.onStep('Creating the collection…');
        const created = await v3<{ id: string; slug: string; revision_number: number; revision_status: string }>(apiKey, 'POST', '/collections', {
            upload_id: upload.id,
            collection_data: payload,
        });
        return { collection_id: created.id, slug: created.slug, owner: input.author, revision_number: created.revision_number, revision_status: created.revision_status };
    }

    input.onStep('Adding a new revision…');
    const revision = await v3<{ revision_number: number; revision_status: string }>(apiKey, 'POST', `/collections/${input.existing.collection_id}/revisions`, {
        upload_id: upload.id,
        collection_data: payload,
    });
    // Keep the title in step with the server's name, as Vortex does on updates.
    await v3(apiKey, 'PATCH', `/collections/${input.existing.collection_id}`, { name }).catch(() => undefined);
    return { ...input.existing, revision_number: revision.revision_number, revision_status: revision.revision_status };
}
